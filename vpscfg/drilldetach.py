def _scenario_normal(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                     **_kw):
    name = "normal"
    token = _acquire(host, operator, "%s: drill scenario normal" % reason, runner)
    marker = scratch + "/normal.ok"
    cmd = _send("true && touch %s" % shlex.quote(marker), guard)
    known = False
    try:
        rc, _out, _err = detach.run(host, token, 1, cmd, token, runner, 30,
                                    unmanaged_ok=unmanaged_ok)
        known = True
        verify_rc, _vo, _ve = runner(host, "test -e %s" % shlex.quote(marker))
        ok = rc == 0 and verify_rc == 0
        return {"name": name, "ok": ok, "detail": "rc=%s verify_rc=%s" % (rc, verify_rc)}
    finally:
        _release_if_known(host, token, runner, known)


def _scenario_slow_start(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                         **_kw):
    name = "slow-start"
    token = _acquire(host, operator, "%s: drill scenario slow-start" % reason, runner)
    marker = scratch + "/slow.ok"
    cmd = _send("sleep 2 && touch %s" % shlex.quote(marker), guard)
    counter = _PollCounter(runner)
    known = False
    try:
        rc, _out, _err = detach.run(host, token, 1, cmd, token, counter, 30,
                                    unmanaged_ok=unmanaged_ok)
        known = True
        verify_rc, _vo, _ve = runner(host, "test -e %s" % shlex.quote(marker))
        ok = rc == 0 and verify_rc == 0 and counter.polls > 1
        return {"name": name, "ok": ok,
                "detail": "rc=%s verify_rc=%s polls=%d" % (rc, verify_rc, counter.polls)}
    finally:
        _release_if_known(host, token, runner, known)


def _scenario_failing(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                      **_kw):
    name = "failing"
    token = _acquire(host, operator, "%s: drill scenario failing" % reason, runner)
    cmd = _send("false", guard)
    known = False
    try:
        rc, _out, _err = detach.run(host, token, 1, cmd, token, runner, 30,
                                    unmanaged_ok=unmanaged_ok)
        known = True
        ok = rc == 1
        return {"name": name, "ok": ok, "detail": "rc=%s" % rc}
    finally:
        if not known:
            _release_if_known(host, token, runner, False)
        elif not _release(host, token, runner):
            raise Refused("drill scenario failing: the lock did not release on a "
                          "known outcome")


def _scenario_lost_ssh(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                       **_kw):
    name = "lost-ssh"
    token = _acquire(host, operator, "%s: drill scenario lost-ssh" % reason, runner)
    marker = scratch + "/lostssh.ok"
    cmd = _send("sleep 1 && touch %s" % shlex.quote(marker), guard)
    kill_wrapper = _ClientKillWrapper(runner)
    known = False
    try:
        rc, _out, _err = detach.run(host, token, 1, cmd, token, kill_wrapper, 30,
                                    unmanaged_ok=unmanaged_ok)
        known = True
        verify_rc, _vo, _ve = runner(host, "test -e %s" % shlex.quote(marker))
        ok = rc == 0 and verify_rc == 0 and kill_wrapper.killed
        return {"name": name, "ok": ok,
                "detail": "rc=%s verify_rc=%s killed=%s"
                          % (rc, verify_rc, kill_wrapper.killed)}
    finally:
        _release_if_known(host, token, runner, known)


def _scenario_timeout(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                      **_kw):
    name = "timeout"
    token = _acquire(host, operator, "%s: drill scenario timeout" % reason, runner)
    marker = scratch + "/timeout.release"
    cmd = _send(
        "while test ! -e %s ; do sleep 0.1 ; done" % shlex.quote(marker), guard)
    gave_up = False
    known = False
    try:
        try:
            detach.run(host, token, 1, cmd, token, runner, 1, unmanaged_ok=unmanaged_ok)
            known = True
            return {"name": name, "ok": False,
                    "detail": "step returned before it was ever stopped"}
        except detach.DetachUnknown:
            gave_up = True
        # The drill's own patience (the `timeout` above) is not a safety bound
        # by itself; a real scratch host's systemd RuntimeMaxSec is. This
        # hermetic sandbox has no systemd, so the same TERM delivery
        # `reconcile --stop` uses is sent directly here to reproduce the
        # OUTCOME a real RuntimeMaxSec kill would leave: rc=143, no human
        # phrase needed (RuntimeMaxSec is automatic, not human-gated either).
        stop_rc, stop_out, _stop_err = runner(host, detach.stop_cmd(token))
        stopped = stop_rc == 0 and detach.STOPPED in (stop_out or "")
        # TERM landed; the runner still needs a moment to write its exit file.
        deadline = time.monotonic() + 5
        st = detach.poll(host, token, 1, runner)
        while st["rc"] is None and time.monotonic() < deadline:
            time.sleep(0.1)
            st = detach.poll(host, token, 1, runner)
        # Known only once the step has an exit code and nothing runs: then the
        # drill may release its own lock; otherwise it stays for reconcile.
        known = st["rc"] is not None and not st["running"]
        ok = gave_up and stopped and st["rc"] == 143 and not st["running"]
        return {"name": name, "ok": ok,
                "detail": "gave_up=%s stopped=%s rc=%s running=%s"
                          % (gave_up, stopped, st["rc"], st["running"])}
    finally:
        _release_if_known(host, token, runner, known)


def _scenario_competing(host, guard, runner, scratch, operator, reason, unmanaged_ok,
                        **_kw):
    name = "competing-op"
    token = _acquire(host, operator, "%s: drill scenario competing-op (first)" % reason,
                     runner)
    refused = False
    try:
        try:
            _acquire(host, operator,
                    "%s: drill scenario competing-op (second)" % reason, runner)
        except Refused:
            refused = True
        return {"name": name, "ok": refused,
                "detail": "second acquire refused=%s" % refused}
    finally:
        _release(host, token, runner)


def _scenario_reconcile_running_then_completed(host, guard, runner, scratch, operator,
                                               reason, unmanaged_ok, prompt=None,
                                               stream=None, **_kw):
    name = "reconcile"
    token = _acquire(host, operator, "%s: drill scenario reconcile" % reason, runner)
    marker = scratch + "/reconcile.release"
    cmd = _send(
        "( while test ! -e %s ; do sleep 0.1 ; done ) & true" % shlex.quote(marker), guard)
    still_running_seen = False
    # Either the reconcile below releases the lock itself (the known, human
    # release path), or something went wrong and it is left retained — never
    # force it from here.
    try:
        detach.run(host, token, 1, cmd, token, runner, 30, unmanaged_ok=unmanaged_ok)
        return {"name": name, "ok": False, "detail": "step never left a child running"}
    except detach.DetachStillRunning:
        pass

    seen_prompts = []

    def counting_prompt(msg):
        seen_prompts.append(msg)
        return prompt(msg) if prompt else input(msg)

    try:
        _vpsexec.reconcile([host], guard, _EMPTY_VPSEXEC_POLICY, ssh=runner,
                          stream=stream, prompt=counting_prompt)
    except Refused as r:
        still_running_seen = "STILL RUNNING" in str(r)
    prompts_before_release = len(seen_prompts)

    runner(host, "touch %s" % shlex.quote(marker))

    rc = _vpsexec.reconcile([host], guard, _EMPTY_VPSEXEC_POLICY, ssh=runner,
                            stream=stream, prompt=counting_prompt)
    phrase_prompts = [m for m in seen_prompts if "RECONCILE:" in m]
    ok = (still_running_seen and prompts_before_release == 0 and rc == 0
          and len(phrase_prompts) == 1)
    return {"name": name, "ok": ok,
            "detail": "still_running_seen=%s prompts_before=%d completed_rc=%s "
                      "phrase_prompts=%d"
                      % (still_running_seen, prompts_before_release, rc,
                         len(phrase_prompts))}


def _scenario_reconcile_stop(host, guard, runner, scratch, operator, reason,
                             unmanaged_ok, prompt=None, stream=None, **_kw):
    name = "reconcile-stop"
    token = _acquire(host, operator, "%s: drill scenario reconcile-stop" % reason,
                     runner)
    marker = scratch + "/stop.release"
    cmd = _send(
        "while test ! -e %s ; do sleep 0.1 ; done" % shlex.quote(marker), guard)
    try:
        detach.run(host, token, 1, cmd, token, runner, 1, unmanaged_ok=unmanaged_ok)
        return {"name": name, "ok": False, "detail": "step ended before --stop"}
    except detach.DetachUnknown:
        pass

    seen_prompts = []

    def counting_prompt(msg):
        seen_prompts.append(msg)
        return prompt(msg) if prompt else input(msg)

    stop_rc = _vpsexec.reconcile([host, "--stop"], guard, _EMPTY_VPSEXEC_POLICY,
                                ssh=runner, stream=stream, prompt=counting_prompt)
    stop_prompts = [m for m in seen_prompts if "STOP:" in m]
    # TERM just landed; the step's own process needs a moment to actually end
    # before a reconcile sees it as settled.
    deadline = time.monotonic() + 5
    while True:
        try:
            release_rc = _vpsexec.reconcile([host], guard, _EMPTY_VPSEXEC_POLICY,
                                            ssh=runner, stream=stream,
                                            prompt=counting_prompt)
            break
        except Refused as r:
            if "STILL RUNNING" not in str(r) or time.monotonic() >= deadline:
                raise
            time.sleep(0.1)
    release_prompts = [m for m in seen_prompts if "RECONCILE:" in m]
    ok = (stop_rc == 0 and len(stop_prompts) == 1 and release_rc == 0
          and len(release_prompts) == 1)
    return {"name": name, "ok": ok,
            "detail": "stop_rc=%s stop_prompts=%d release_rc=%s release_prompts=%d"
                      % (stop_rc, len(stop_prompts), release_rc, len(release_prompts))}


_SCENARIO_FNS = [
    _scenario_normal, _scenario_slow_start, _scenario_failing, _scenario_lost_ssh,
    _scenario_timeout, _scenario_competing, _scenario_reconcile_running_then_completed,
    _scenario_reconcile_stop,
]



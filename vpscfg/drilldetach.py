def _authorize(guard, host):
    """Resolve `host` to its canonical governed name and refuse unless BOTH
    the canonical host's posture is `test` and it is named in the governor's
    `drill_hosts`. Raises Refused for every other case, including a missing
    `drill_hosts` key. Nothing here contacts a host."""
    if not isinstance(host, str) or not host:
        raise Refused("invalid host %r" % (host,))
    policy = guard.policy
    hosts_cfg = policy.get("hosts", {}) or {}
    if host not in hosts_cfg:
        raise Refused("host %r has no governor entry — drill detach refuses an "
                      "unknown host" % (host,))
    aliases = _vpsexec.governor_aliases(hosts_cfg)  # {alias: canonical}
    canonical = aliases.get(host, host)
    cfg = hosts_cfg.get(canonical)
    if not isinstance(cfg, dict):
        raise Refused("host %r resolves to %r, which has no governor entry"
                      % (host, canonical))
    guard.assert_verb("drill")
    posture = cfg.get("posture", "frozen")
    if posture != "test":
        raise Refused(
            "host %r (canonical %r) posture is %r — vpscfg drill detach runs only "
            "on posture 'test', never on a frozen, lockdown or released host"
            % (host, canonical, posture))
    drill_hosts = policy.get("drill_hosts")
    if not isinstance(drill_hosts, list) or not all(isinstance(h, str) for h in drill_hosts):
        raise Refused(
            "governor key 'drill_hosts' is missing or is not a list of host names — "
            "vpscfg drill detach refuses until it is explicitly configured")
    if canonical not in drill_hosts:
        raise Refused(
            "host %r (canonical %r) is not listed under the governor's drill_hosts "
            "— vpscfg drill detach refuses" % (host, canonical))
    if policy.get("mode") == "lockdown":
        raise Refused("mode is lockdown — no mutations, drill detach included")
    if not policy.get("mutation_enabled", False):
        raise Refused("mutation_enabled is false — master switch off")
    return canonical


def _unmanaged_ok(guard, canonical):
    listed = guard.policy.get("allow_unmanaged_steps") or []
    return isinstance(listed, list) and canonical in listed



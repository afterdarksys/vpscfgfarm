def _parse(argv):
    if not argv or argv[0] != "detach":
        raise Refused("usage: vpscfg drill detach <host> [--run] [--reason TEXT]")
    if len(argv) < 2 or argv[1].startswith("-"):
        raise Refused("usage: vpscfg drill detach <host> [--run] [--reason TEXT]")
    host = argv[1]
    run = False
    reason = None
    index = 2
    while index < len(argv):
        token = argv[index]
        if token == "--run":
            run = True
            index += 1
            continue
        if token == "--reason":
            if reason is not None or index + 1 >= len(argv):
                raise Refused("drill detach --reason text")
            reason = argv[index + 1]
            index += 2
            continue
        raise Refused("unknown drill detach flag %r" % (token,))
    return host, run, reason


def _print_plan(host, canonical):
    print("DRILL DETACH PLAN for %s (canonical %s)" % (host, canonical))
    print("  this door does not remove the scratch directory it creates")
    for idx, (name, desc) in enumerate(SCENARIOS, 1):
        print("  %d. %-14s %s" % (idx, name, desc))
    return 0


def cli(guard, argv, runner=None, prompt=None, stream=None):
    host, run, reason = _parse(argv)
    canonical = _authorize(guard, host)
    if not run:
        return _print_plan(host, canonical)
    return execute(guard, host, canonical, reason, runner=runner, prompt=prompt,
                   stream=stream)



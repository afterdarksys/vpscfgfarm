VERIFIER = "vpscfg drill detach"

_LABEL_RE = re.compile(r"^vpscfg-drill-[a-f0-9]{16}\Z")
_SCRATCH_RE = re.compile(r"^/tmp/vpscfg-drill-[A-Za-z0-9]+\Z")
_MKTEMP = "mktemp -d /tmp/vpscfg-drill-XXXXXXXX"

# Every scenario body is built only from these words/punctuation plus a
# numeric literal or a path under the drill's own scratch directory.
_SAFE_WORDS = {"true", "false", "test", "sleep", "touch", "while", "do", "done",
               "!", "-e", "&&", "&", ";", "(", ")"}
_SAFE_NUM_RE = re.compile(r"^[0-9]+(?:\.[0-9]+)?\Z")
_SAFE_PATH_RE = re.compile(r"^/tmp/vpscfg-drill-[A-Za-z0-9._/-]*\Z")

_EMPTY_VPSEXEC_POLICY = {"groups": {}, "runbooks": [], "deny_extra": [], "risky_extra": [],
                         "files": []}

SCENARIOS = [
    ("normal", "a normal step: rc 0, verify passes"),
    ("slow-start", "a step whose result takes more than one poll to arrive; "
                   "verify succeeds only after the extra poll(s)"),
    ("failing", "a step that fails (rc 1); the lock is released on a known outcome"),
    ("lost-ssh", "the drill kills its own ssh client mid-step; the door re-attaches "
                 "with backoff and reads the real rc"),
    ("timeout", "a step that outlives the drill's own patience; the lock is retained "
                "as unknown, then ended the way a real RuntimeMaxSec would, and the "
                "real rc (143) is read back"),
    ("competing-op", "a second operation is refused while the first still holds the "
                     "host lock"),
    ("reconcile", "a retained lock reports STILL RUNNING, then — once the step ends "
                  "— COMPLETED; the release phrase is typed by a human at `vpsexec "
                  "reconcile`, never by this drill"),
    ("reconcile-stop", "`vpsexec reconcile <host> --stop` ends a running step; the "
                       "stop phrase, too, is typed by a human"),
]



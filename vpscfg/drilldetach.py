def execute(guard, host, canonical, reason, runner=None, prompt=None, stream=None):
    if not isinstance(reason, str) or reason.strip() == "":
        raise Refused("drill detach --run requires --reason")
    guard.assert_read_only_or_verified("drill")
    runner = runner or default_runner
    unmanaged_ok = _unmanaged_ok(guard, canonical)
    operator = journal.operator()
    label = "vpscfg-drill-" + secrets.token_hex(8)
    assert _LABEL_RE.fullmatch(label)

    # Journaled before the first host contact (L5): a drill that creates a
    # scratch dir or takes a lock is always on record, or it does not start.
    try:
        journal.append("drill", {"event": "drill_detach_start", "host": canonical,
                                 "label": label, "reason": reason, "operator": operator,
                                 "scenarios": [name for name, _ in SCENARIOS]})
    except Exception:
        print("DRILL FAILED: the start was not journaled — nothing was contacted",
              file=sys.stderr)
        return 1
    scratch = _make_scratch(canonical, runner)
    results = []
    for fn in _SCENARIO_FNS:
        try:
            outcome = fn(canonical, guard, runner, scratch, operator, reason,
                        unmanaged_ok, prompt=prompt, stream=stream)
        except Exception as e:  # a scenario's own unexpected failure is evidence too
            outcome = {"name": fn.__name__, "ok": False, "detail": str(e)[:300]}
        results.append(outcome)
        try:
            journal.append("drill", {
                "event": "drill_detach_scenario", "host": canonical, "label": label,
                "reason": reason, "scenario": outcome.get("name"), "ok": outcome.get("ok"),
                "detail": secretmask.mask(str(outcome.get("detail") or ""))[:500]})
        except Exception:
            print("DRILL FAILED: scenario %r was not journaled" % outcome.get("name"),
                  file=sys.stderr)
            return 1

    overall_ok = all(r.get("ok") for r in results)
    receipt = {
        "event": "drill_detach_receipt", "kind": "drill-detach", "host": canonical,
        "label": label, "reason": reason, "verifier": VERIFIER, "verified": overall_ok,
        "scenarios": [{"name": r.get("name"), "ok": r.get("ok")} for r in results],
        "tested_at": datetime.now(timezone.utc).isoformat(),
    }
    try:
        journal.append("drill", receipt)
    except Exception:
        print("DRILL FAILED: receipt was not journaled", file=sys.stderr)

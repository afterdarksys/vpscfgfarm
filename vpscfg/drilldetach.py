"""`vpscfg drill detach <host>`: the automated version of docs/RECOVERY.md's
controlled scratch-host drill for the detached-step machinery (vpscfg/detach.py,
vpscfg/lock.py, `vpsexec reconcile`). It never invents new remote shell: every
scenario is built only from `sleep`/`true`/`false`/`test`/`while`/`done` and a
file under `/tmp/vpscfg-drill-*`, and every guarantee it re-proves is exercised
through the SAME reviewed functions a real mutation or a real reconcile uses
(`detach.run`, `lock.acquire`/`release`, `vpsexec.reconcile`) — this module adds
no new way to launch, stop or release anything.

Opt-in is two independent switches, both required, checked BEFORE any host is
contacted: the (canonical, alias-resolved) host's governor posture must be
`test`, and it must be named in a new governor key `drill_hosts: [...]`. This
command never uses `--break-glass` and never opens an incident.

Threats:
  - Protects against: drilling a host that is not explicitly opted in twice
    over (posture `test` AND `drill_hosts`, aliases resolved to canonical
    first, so naming a frozen host's alias in `drill_hosts` cannot launder
    it — the posture check still reads the alias's own, validated-equal,
    canonical posture); every refusal happens before any transport call
    (asserted by a test with a dial-counting transport); a scenario step
    that is anything other than sleep/true/false/test/while/done and a path
    under the drill's own scratch directory (`_assert_safe_step`, defense in
    depth — these strings are generated by this module, never from input,
    but checked anyway); a reconcile or stop phrase ever being typed by this
    module itself — scenarios 7 and 8 call `vpsexec.reconcile` and let IT
    print the phrase and read it from `prompt` (which defaults to the real
    `input()`, i.e. the operator's own terminal); this module's own source
    never builds either phrase itself — it only ever reads one back, as a
    plain substring check on what `vpsexec.reconcile` already printed, to
    count prompts in a test (checked by a test that greps for the
    phrase-building shape, not for the substring itself); a stray lock
    surviving a scenario
    that completed (every scenario releases its own lock itself, by calling
    `lock.release` directly once it has established a known outcome, or by
    driving `vpsexec.reconcile` to the human-typed release when the outcome
    was only established as retained/uncertain).
  - Does NOT protect against: a host that lies about what ran (same as every
    other door in this tool — the host is trusted); a real systemd
    `RuntimeMaxSec` being honoured — scenario 5 ("timeout") cannot exercise
    systemd on a hermetic sandbox with no systemd at all, so it reproduces
    the OUTCOME (a step ended by TERM reports rc=143) using the same
    `detach.stop_cmd` a real `RuntimeMaxSec` kill would also use, which
    proves the door reports rc=143 correctly but is not proof that the real
    scratch host's systemd unit is actually bounded — that is still the
    operator's job on the real scratch host (docs/RECOVERY.md, "Release validation").
"""

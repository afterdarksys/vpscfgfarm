def default_runner(host, command, timeout=None):
    result = subprocess.run(
        ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", host, command],
        capture_output=True, timeout=timeout or 120)
    if result.returncode == 255:
        raise OSError("SSH connection lost; remote completion is unknown")
    return (result.returncode,
            result.stdout.decode("utf-8", "replace"),
            result.stderr.decode("utf-8", "replace"))


class _ClientKillWrapper(object):
    """Wraps a real runner for scenario 4. The FIRST poll call after the step
    is launched is preceded by this module killing a real local subprocess
    that stands in for the operator's own ssh client — then it raises the
    exact connection-lost error a dropped ssh session raises. Every call
    before and after goes straight to the real runner, untouched: this
    wrapper never fakes a result, it only drops the one call it fires on, so
    `detach.run`'s own backoff and re-attach is what has to recover."""

    def __init__(self, runner):
        self._runner = runner
        self._fired = False
        self.killed = False

    def __call__(self, host, command, timeout=None):
        if not self._fired and "VPSCFG-STATE" in command:
            self._fired = True
            proc = subprocess.Popen(["sleep", "5"])
            proc.kill()
            proc.wait()
            self.killed = True
            raise OSError("SSH connection lost; remote completion is unknown "
                          "(drill killed its own ssh client)")
        return self._runner(host, command, timeout=timeout)


class _PollCounter(object):
    """Counts poll calls so scenario 2 can show the result arrived only after
    more than one poll, without reaching into `detach.run`'s internals."""

    def __init__(self, runner):
        self._runner = runner
        self.polls = 0

    def __call__(self, host, command, timeout=None):
        if "VPSCFG-STATE" in command:
            self.polls += 1
        return self._runner(host, command, timeout=timeout)


def _assert_safe_step(command):
    """Defense in depth: every scenario body this module sends must be built
    only from sleep/true/false/test/while/done, punctuation and a path under
    the drill's own scratch directory. These strings are generated by this
    module, never from input — checked anyway."""
    if not isinstance(command, str) or not command.strip():
        raise Refused("drill detach step refused: empty command")
    for word in command.split():
        if (word in _SAFE_WORDS or _SAFE_NUM_RE.match(word)
                or _SAFE_PATH_RE.match(word)):
            continue
        raise Refused(
            "drill detach step refused: %r is outside sleep/true/false, "
            "test/while/done, and a file under /tmp/vpscfg-drill-*" % (word,))


def _send(command, guard):
    """Defense-in-depth gate for every scenario body: the vocabulary check
    plus the SAME deny-always floor every mutation's body goes through."""
    _assert_safe_step(command)
    deny_scan(command, guard.deny_patterns())
    return command


def _make_scratch(host, runner):
    rc, out, _err = runner(host, _MKTEMP)
    text = (out or "").strip()
    if rc != 0 or (out or "").count("\n") > 1 or not _SCRATCH_RE.fullmatch(text):
        raise Refused("drill detach could not create a scratch directory on %s" % host)
    return text


def _acquire(host, operator, reason, runner):
    return lock.acquire(host, operator, reason, runner=runner)


def _release(host, token, runner):
    return lock.release(host, runner=runner, token=token, op_dir=detach.op_dir(token))


def _release_if_known(host, token, runner, known):
    """Release this scenario's own lock ONLY on a known outcome. When
    detach.run raised on an unknown one (lost transport, a step still
    running, a refusal mid-way), the lock is retained for `vpsexec reconcile`
    and a human's phrase — the docstring's rule, and the door's own (L5)."""
    if known:
        _release(host, token, runner)
    else:
        print("drill detach: operation %s on %s ended with an unknown outcome — its lock "
              "is RETAINED; settle it with: vpsexec reconcile %s" % (token[:8], host, host),
              file=sys.stderr)



"""`vpsrun release new <name> --from <policy.yaml>[,...]` — scaffold plays/ and
a releases/ file from a committed runbook policy, so a production mismatch
costs an edit to one declarative line instead of a hand-written play.

It reads policy files and writes play/release files. It never contacts a
host, never writes under `policies/`, never mints a grant, and never invokes
the door with `--run`. Overwriting an existing file is refused unless
`--replace` is given AND the existing file carries this module's own header
(the generator version, the source policy's sha256 and the sha256 of the
file's own body below the header) AND that body still hashes to it — a
hand-edited file is never silently replaced.

Every runbook step is copied into the play, in order, with its timeout (an
action step's template timeout when the runbook gives none). Rollback steps
go only under the release's `on_fail`. A STOP / probe / precheck / check step
(the same words `runbook lint` uses: its STOP_RE and PROBE_WHY_RE) gets an
`id:`. An OPTIONAL step ("optional", "only if") after one gets a `when:` stub
pointing at it, whose placeholder regex matches nothing: `runbook lint` fails
any play still carrying it, so a stub can never silently skip a step. A
required step never gets a `when:`.

Threats:
  - Protects against: a `--from` path that escapes `policies/` (symlink, `..`,
    an absolute path elsewhere) — refused before the file is even read; a
    second `release new` clobbering a play a human has since hand-edited
    (the header pins the body's sha256 and --replace re-hashes it); writing
    through a symlink planted at an output path (lstat refuses a symlink,
    and the file is created with O_EXCL|O_NOFOLLOW after any old copy of
    our own is unlinked); a generated step silently skipped (no `when:` on a
    required step; a stub fails lint); YAML injection through a name or a
    value (every scalar is written as JSON, a YAML flow scalar); writing
    into `policies/` (the one directory this module never opens for
    writing); contacting a host or spending a grant (lint and preflight here
    always run `--index-only`; nothing here ever passes `--run` to the door).
  - Does NOT protect against: a policy that is syntactically fine but a bad
    idea — `runbook lint`/`preflight` catch what they catch; a human still
    reads the generated play before approving it with `vpsrun release`; a
    race with another writer in the same directory between the overwrite
    check and the write (the directory is the operator's own estate).
"""

import hashlib
import json
import math
import os
import re
import stat
import subprocess
import sys
from pathlib import Path

import yaml

from . import estate as _estate
from .gates import Refused

GENERATOR = "vpsrun release new"
GENERATOR_VERSION = 2
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
# The placeholder a `when:` stub carries: it matches nothing real on purpose,
# and `runbook lint` fails a play that still has it (V5).
STUB_REGEX = "CHANGEME-REVIEW-THIS-CONDITION"
HEADER_RE = re.compile(
    r"^# generated by (?P<gen>.+?) v(?P<ver>\d+) from policy sha256:(?P<sha>[0-9a-f]{64})"
    r"(?: body sha256:(?P<body>[0-9a-f]{64}))? — do not hand-edit; re-run with "
    r"--replace after reviewing the diff\n")
DEFAULT_GRANT_TTL = "12h"
# pg_dump's free-space sizing from the index (docs/ACTIONS.md): size x 1.2.
DUMP_HEADROOM = 1.2


def _header(policy_sha256, body):
    return ("# generated by %s v%d from policy sha256:%s body sha256:%s — do not "
            "hand-edit; re-run with --replace after reviewing the diff\n"
            % (GENERATOR, GENERATOR_VERSION, policy_sha256,
               hashlib.sha256(body.encode("utf-8")).hexdigest()))


def _own_header(text):
    """(generator, version, policy_sha256, body_sha256_or_None) if `text`
    starts with a header this module could have written, else None."""
    m = HEADER_RE.match(text)
    if not m or m.group("gen") != GENERATOR:
        return None
    return m.group("gen"), int(m.group("ver")), m.group("sha"), m.group("body")


def check_name(name):
    name = str(name)
    if not NAME_RE.match(name) or ".." in name:
        raise Refused("release new: name %r must be 1-64 of [A-Za-z0-9._-], starting "
                      "with a letter or digit (no paths)" % (name,))
    return name


def resolve_policy_path(raw, estate_root=None):
    """`raw` (as given to --from) resolved to a real file strictly inside
    <estate>/policies/ (which includes policies/actions/). Refuses a path
    that escapes it by '..', a symlink, or being absolute elsewhere."""
    estate_root = Path(estate_root or _estate.root())
    policies_root = (estate_root / "policies").resolve()
    given = Path(raw)
    candidate = given if given.is_absolute() else estate_root / given
    try:
        resolved = candidate.resolve(strict=True)
    except OSError as e:
        raise Refused("release new: cannot read policy %r (%s)"
                      % (raw, e.strerror or e))
    if not resolved.is_file():
        raise Refused("release new: policy %r is not a regular file" % (raw,))
    try:
        rel = resolved.relative_to(policies_root)
    except ValueError:
        raise Refused("release new: policy %r resolves outside policies/ — refused"
                      % (raw,))
    return resolved, str(rel)


def _load_policy(path):
    raw = path.read_bytes()
    try:
        doc = yaml.safe_load(raw)
    except yaml.YAMLError as e:
        raise Refused("release new: %s does not parse as YAML (%s)" % (path, e))
    if not isinstance(doc, dict) or doc.get("version") != 1:
        raise Refused("release new: %s is not a version-1 policy" % path)
    runbooks = doc.get("runbooks")
    if not isinstance(runbooks, list) or not runbooks:
        raise Refused("release new: %s has no runbooks: list" % path)
    for n, entry in enumerate(runbooks, 1):
        if not isinstance(entry, dict):
            raise Refused("release new: %s runbook %d is not a mapping" % (path, n))
    return doc, raw, runbooks


def _lint_words():
    """The words `runbook lint` reads in a `why:` (one definition for both
    tools, V6): a STOP step and a probe/precheck/check step must classify as
    a read there, and are the anchors for a `when:` stub here."""
    from . import runbookcheck
    return runbookcheck.STOP_RE, runbookcheck.PROBE_WHY_RE, runbookcheck.OPTIONAL_RE


def _is_stop_step(entry):
    stop_re, probe_re, _ = _lint_words()
    why = str(entry.get("why") or "")
    return bool(stop_re.search(why) or probe_re.search(why))


def _is_optional(entry):
    return bool(_lint_words()[2].search(str(entry.get("why") or "")))


def _is_rollback(entry):
    why = str(entry.get("why") or "").lower()
    return bool(entry.get("rollback")) or "(rollback only" in why


def _hosts_list(entry):
    hosts = entry.get("hosts", entry.get("host"))
    return hosts if isinstance(hosts, list) else [hosts] if hosts else []


def _action_timeout(entry):
    """The template timeout of an action entry, or None (the policy itself is
    then refused by lint, which reports why)."""
    from . import actions
    hosts = _hosts_list(entry)
    if not hosts:
        return None
    try:
        return actions.expand(entry.get("action"), entry.get("with"), str(hosts[0]),
                              "release new").timeout
    except (Refused, ValueError):
        return None


def _step_flags(entry):
    flags = []
    if entry.get("break_glass"):
        flags.append("--break-glass")
    timeout = entry.get("timeout")
    if timeout is None and "action" in entry:
        timeout = _action_timeout(entry)
    if timeout is not None:
        flags.append("--timeout=%s" % timeout)
    return flags


def build_play(policy_ref, runbooks):
    """-> (steps, on_fail) for one play scaffolded from one policy's runbooks.
    Rollback entries are never put in the play: `plays/README.md`'s rule is
    rollback only under a release's on_fail. Only an OPTIONAL step after a
    STOP/probe step gets a `when:` stub; a required step never does."""
    steps, on_fail, last_stop_id = [], [], None
    for n, entry in enumerate(runbooks, 1):
        if _is_rollback(entry):
            on_fail.append({"runbook": Path(policy_ref).name, "step": n})
            continue
        hosts = ",".join(str(h) for h in _hosts_list(entry))
        why = str(entry.get("why") or "step %d" % n)
        step = {"hosts": hosts, "why": why, "flags": _step_flags(entry)}
        if "action" in entry or "with" in entry:
            step["action"] = entry.get("action")
            step["with"] = entry.get("with") or {}
        else:
            step["cmd"] = entry.get("cmd")
        if _is_stop_step(entry):
            step["id"] = "s%d" % n
            last_stop_id = step["id"]
        elif _is_optional(entry) and last_stop_id is not None:
            # A stub a human must read and either replace with a real
            # condition or delete; lint fails the play until then.
            step["when"] = "%s reports %s" % (last_stop_id, STUB_REGEX)
        steps.append(step)
    return steps, on_fail


def _scalar(value):
    """A YAML flow scalar/collection for any value written into a generated
    file: JSON is valid YAML flow syntax, double-quoted strings cannot be
    read as another type, and — unlike yaml.safe_dump — it never appends a
    `...` document-end marker that would break the hand-assembled file."""
    return json.dumps(value, sort_keys=True)


def _step_yaml(step):
    lines = ["  - hosts: %s" % _scalar(step["hosts"])]
    if "action" in step:
        lines.append("    action: %s" % _scalar(step["action"]))
        lines.append("    with: %s" % _scalar(step["with"]))
    else:
        lines.append("    cmd: %s" % _scalar(step["cmd"]))
    if step.get("flags"):
        lines.append("    flags: %s" % _scalar(step["flags"]))
    if step.get("id"):
        lines.append("    id: %s" % _scalar(step["id"]))
    if step.get("when"):
        lines.append("    when: %s" % _scalar(step["when"]))
    lines.append("    why: %s" % _scalar(step["why"]))
    return "\n".join(lines)


def render_play(reason, steps, policy_sha256):
    body = ["version: 1", "reason: %s" % _scalar(reason), "steps:"]
    body += [_step_yaml(s) for s in steps]
    text = "\n".join(body) + "\n"
    return _header(policy_sha256, text) + text


def render_release(name, play_names, policy_refs, on_fail, reason, grant_ttl, policy_sha256):
    # `policies:` and on_fail name a policy by its bare file name: vpsrun's
    # NAME_RE refuses a path, and it looks in policies/actions/ itself.
    lines = ["version: 1", "reason: %s" % _scalar(reason),
             "policies: %s" % _scalar([Path(r).name for r in policy_refs]),
             "grant_ttl: %s" % _scalar(grant_ttl), "plays:"]
    lines += ["  - %s" % _scalar(p) for p in play_names]
    if on_fail:
        lines.append("on_fail:")
        for o in on_fail:
            lines.append("  - runbook: %s" % _scalar(Path(o["runbook"]).name))
            lines.append("    step: %d" % o["step"])
    text = "\n".join(lines) + "\n"
    return _header(policy_sha256, text) + text


def _refuse_bad_overwrite(path, replace):
    """Refuse unless `path` is absent, or --replace and it is an unedited
    file of our own. A symlink at the path is refused either way."""
    try:
        st = os.lstat(str(path))
    except FileNotFoundError:
        return
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
        raise Refused("release new: %s is a symlink or not a regular file — refused"
                      % path)
    if not replace:
        raise Refused("release new: %s already exists — refusing to overwrite it. "
                      "Pass --replace once you have reviewed the diff." % path)
    existing = _read_nofollow(path)
    own = _own_header(existing)
    if own is None:
        raise Refused("release new: %s already exists and was not written by %s — "
                      "--replace only rewrites files this tool generated itself."
                      % (path, GENERATOR))
    body_sha = own[3]
    if body_sha is None:
        raise Refused("release new: %s was written by an older %s (v%d) with no body "
                      "hash, so a hand edit cannot be ruled out — review it and delete "
                      "it by hand to regenerate" % (path, GENERATOR, own[1]))
    body = existing.split("\n", 1)[1] if "\n" in existing else ""
    if hashlib.sha256(body.encode("utf-8")).hexdigest() != body_sha:
        raise Refused("release new: %s was edited by hand since it was generated (its "
                      "body no longer matches the header's sha256) — --replace never "
                      "discards hand edits; move them into the policy, or delete the "
                      "file yourself" % path)


def _read_nofollow(path):
    fd = os.open(str(path), os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    with os.fdopen(fd, "r", encoding="utf-8") as f:
        return f.read()


def _write(path, text):
    """Create `path` fresh: never through a symlink, never over a file that
    appeared since the overwrite check (O_EXCL). An old copy of our own was
    already vetted by _refuse_bad_overwrite and is unlinked first."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        st = os.lstat(str(path))
    except FileNotFoundError:
        st = None
    if st is not None:
        if not stat.S_ISREG(st.st_mode):
            raise Refused("release new: %s is a symlink or not a regular file — refused"
                          % path)
        os.unlink(str(path))
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL
                 | getattr(os, "O_NOFOLLOW", 0), 0o644)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


def _default_vpsexec_runner(argv):
    """`vpsexec ARGV` as a child of THIS already-pinned interpreter (vpsrun
    re-execs through the real interpreter before importing this module, so
    sys.executable here is already the verified binary)."""
    exe = str(Path(_estate.TOOL_ROOT) / "vpsexec")
    r = subprocess.run([sys.executable, "-I", exe] + argv, capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def default_lint(policy_path, plays_dir=None):
    argv = ["runbook", "lint", str(policy_path)]
    if plays_dir:
        argv += ["--plays", str(plays_dir)]
    return _default_vpsexec_runner(argv)


def default_preflight_index_only(policy_path):
    # --index-only: never dials a host (S11, adversarial test 8).
    return _default_vpsexec_runner(["runbook", "preflight", str(policy_path), "--index-only"])


def default_preflight_live(policy_path):
    return _default_vpsexec_runner(["runbook", "preflight", str(policy_path)])


def gate(policy_paths, lint_fn, preflight_fn):
    """Run lint_fn and preflight_fn over every policy path; -> (exit_code,
    text) combined by the worst verdict (NO-GO beats GO-WITH-WARNINGS beats
    GO), text carrying every sub-report in order."""
    worst, parts = 0, []
    for p in policy_paths:
        for fn in (lint_fn, preflight_fn):
            rc, text = fn(p)
            worst = max(worst, rc)
            parts.append(text.rstrip())
    return worst, "\n".join(parts)


VERDICT_NAME = {0: "GO", 1: "GO-WITH-WARNINGS", 2: "NO-GO"}


def dump_sizing(runbooks, index_dir, max_age, now=None):
    """Advice, never authority (S11): for each pg_dump step without
    `min_free_gb`, the size a fresh index records for its database x 1.2,
    rounded up to whole GB, as the `with:` line to add to the POLICY (the
    play's `with:` must equal the policy's, so this module never writes it).
    -> [text]."""
    from . import indexstore
    out = []
    for n, entry in enumerate(runbooks, 1):
        params = entry.get("with") if isinstance(entry.get("with"), dict) else {}
        if entry.get("action") != "pg_dump" or "min_free_gb" in params:
            continue
        for host in _hosts_list(entry):
            doc, age, reason = indexstore.cache_status(str(host), index_dir, max_age, now=now)
            size = _db_size(doc, params.get("container"), params.get("db"))
            if size is None:
                out.append("step %d (pg_dump %s on %s): no min_free_gb, and the index cannot "
                           "size it (%s)" % (n, params.get("db"), host,
                                             reason or "database not in the index"))
                continue
            gb = max(1, int(math.ceil(size * DUMP_HEADROOM / float(1 << 30))))
            out.append("step %d (pg_dump %s on %s): the index (%dh old) records %d bytes; "
                       "add `min_free_gb: %d` to its with: in the policy (size x %.1f)"
                       % (n, params.get("db"), host, int((age or 0) // 3600), size, gb,
                          DUMP_HEADROOM))
    return out


def _db_size(doc, container, database):
    pg = ((doc or {}).get("sections") or {}).get("postgres")
    if not isinstance(pg, dict) or "error" in pg or "unavailable" in pg:
        return None
    for inst in pg.get("instances") or []:
        if inst.get("container") != container or "error" in inst:
            continue
        for db in inst.get("databases") or []:
            size = db.get("size_bytes")
            if db.get("name") == database and isinstance(size, int) \
                    and not isinstance(size, bool) and size >= 0:
                return size
    return None


def new(name, from_arg, estate_root=None, replace=False, lint_fn=None, preflight_fn=None,
        plays_dir=None, releases_dir=None, reason=None, index_dir=None, index_max_age=None,
        now=None):
    """Scaffold plays/<name>-<policy-stem>.yaml (one per policy) and
    releases/<name>.yaml from the policies named by --from (comma-separated).
    Never contacts a host, never writes under policies/, never mints.
    Returns {"plays": [...], "release": path, "verdict", "exit_code", "report",
    "advice": [...]}."""
    from . import indexstore
    name = check_name(name)
    estate_root = Path(estate_root or _estate.root())
    plays_dir = Path(plays_dir or (estate_root / "plays"))
    releases_dir = Path(releases_dir or (estate_root / "releases"))
    index_dir = Path(index_dir or (estate_root / indexstore.CACHE_DIRNAME))
    max_age = index_max_age or indexstore.max_age_seconds({})
    lint_fn = lint_fn or default_lint
    preflight_fn = preflight_fn or default_preflight_index_only

    raw_names = [p.strip() for p in str(from_arg).split(",") if p.strip()]
    if not raw_names:
        raise Refused("release new: --from needs at least one policy.yaml")

    play_paths, play_names, policy_refs, resolved_paths = [], [], [], []
    on_fail_all, advice = [], []
    for raw in raw_names:
        path, ref = resolve_policy_path(raw, estate_root)
        doc, policy_raw, runbooks = _load_policy(path)
        sha = hashlib.sha256(policy_raw).hexdigest()
        steps, on_fail = build_play(ref, runbooks)
        play_name = "%s-%s" % (name, path.stem)
        play_text = render_play(
            reason or ("release new: scaffolded from %s" % ref), steps, sha)
        play_path = plays_dir / ("%s.yaml" % play_name)
        _refuse_bad_overwrite(play_path, replace)
        play_paths.append((play_path, play_text))
        play_names.append(play_name)
        policy_refs.append(ref)
        resolved_paths.append(path)
        on_fail_all += on_fail
        advice += ["%s %s" % (Path(ref).name, a)
                   for a in dump_sizing(runbooks, index_dir, max_age, now=now)]

    release_sha = hashlib.sha256(
        "".join(sorted(policy_refs)).encode("utf-8")).hexdigest()
    release_text = render_release(
        name, play_names, policy_refs, on_fail_all,
        reason or ("release new: scaffolded from %s" % ", ".join(policy_refs)),
        DEFAULT_GRANT_TTL, release_sha)
    release_path = releases_dir / ("%s.yaml" % name)
    _refuse_bad_overwrite(release_path, replace)

    # Nothing written until every refusal above has had its chance: a failed
    # release new leaves no half-scaffolded files behind.
    for play_path, play_text in play_paths:
        _write(play_path, play_text)
    _write(release_path, release_text)

    exit_code, report_text = gate(resolved_paths, lint_fn, preflight_fn)
    if advice:
        report_text += "\nADVICE (from the index; edit the policy, then re-run with " \
                       "--replace):\n" + "\n".join("  " + a for a in advice)
    return {"plays": [str(p) for p, _ in play_paths], "release": str(release_path),
            "verdict": VERDICT_NAME[exit_code], "exit_code": exit_code,
            "report": report_text, "advice": advice}
